/**
 * Task 08 campaign UI state (framework-free). Owns the progression service, menu navigation and
 * the selected class/map. React components only read this state and call these actions; all
 * reward, save and scheduling logic lives in the campaign/profile/persistence modules.
 */
/** Task 13: `hub` (was `play`), plus separate Equipment and Talents pages. */
export type MenuPage =
  | 'hub'
  | 'character'
  | 'equipment'
  | 'talents'
  | 'maps'
  | 'shop'
  | 'forge'
  | 'pets'
  | 'progression'
  | 'settings';
export interface CampaignUiState {
  readonly page: MenuPage;
  /**
   * Task 13 (presentation only): class shown by the Equipment and Talents pages when opened from
   * a character card; null = the selected class.
   */
  readonly viewClass: CharacterClass | null;
  /** Task 19 (presentation only): item preselected when the forge is opened from an item. */
  readonly forgeItem: string | null;
  /** Task 20 (presentation only): shop tab to open with (e.g. 'pets'); null = default. */
  readonly shopTab: string | null;
  readonly selectedMapId: number;
  readonly progression: ProgressionState;
  /** Validated import waiting for the player's confirmation (nothing replaced yet). */
  readonly pendingImport: Readonly<{ profile: PlayerProfile; fileName: string }> | null;
  /** Last save-management message for the player (null = none). */
  readonly saveMessage: Readonly<{ tone: 'ok' | 'error'; text: string }> | null;
  /** Commit result of the latest finished campaign run (results screen). */
  readonly lastResult: Readonly<{ runId: string; result: RunResult; commit: CommitResult }> | null;
}

/** Task 08.5: the persisted part of the in-memory run statistics (whole-number damage). */
export function summarizeRunStats(stats: RunStatsSnapshot): RunStatsSummary {
  return Object.freeze({
    damageDealt: Math.round(stats.damageDealt),
    damageTaken: Math.round(stats.damageTaken),
    topSources: Object.freeze(
      stats.bySource
        .slice(0, RUN_STATS_SUMMARY_LIMITS.topSources)
        .map((s) => Object.freeze({ source: s.source, damage: Math.round(s.damage) })),
    ),
    deathTime: stats.deathTime,
    reviveUsed: stats.reviveUsed,
    lowHpMoments: stats.lowHpMoments,
  });
}
/** World snapshot → profile run result (elapsed capped at the map duration). */
export function runResultFrom(
  world: GameplaySnapshot,
  outcome?: RunResult['outcome'],
): RunResult | null {
  const c = world.campaign;
  if (!c || !c.runId) return null;
  const status = outcome ?? c.status;
  if (status === 'active') return null;
  return Object.freeze({
    runId: c.runId,
    mapId: c.mapId,
    characterClass: world.character.characterClass,
    outcome: status,
    elapsed: Math.min(c.resolvedAt ?? world.time, c.duration),
    kills: world.kills,
    eliteKills: c.eliteKills,
    bossKilled: c.bossKilled,
    runLevel: world.progression.level,
    stats: summarizeRunStats(world.runStats),
    // Task 11: coins collected this run (converted to Gold once, with the result).
    coins: world.coins.collected,
  });
}

/**
 * Task 08.5 §4.2: a fresh 32-bit seed per run, generated by the UI (never inside the
 * simulation). Uses the browser CSPRNG when available.
 */
export function generateRunSeed(): number {
  try {
    const a = new Uint32Array(1);
    globalThis.crypto.getRandomValues(a);
    return a[0];
  } catch {
    return Math.floor(Math.random() * (MAX_UI_SEED + 1));
  }
}
/** Browser download of a JSON text file; false if the browser refused. */
export function downloadJson(filename: string, json: string): boolean {
  try {
    const url = URL.createObjectURL(new Blob([json], { type: 'application/json' }));
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.append(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 0);
    return true;
  } catch {
    return false;
  }
}
let service: ProgressionService | null = null;
let state: CampaignUiState | null = null;
const listeners = new Set<() => void>();

function ensure(): CampaignUiState {
  if (!service) {
    service = createProgressionService(createSaveStore());
    const initial = service.getState();
    state = Object.freeze({
      page: 'hub',
      viewClass: null,
      forgeItem: null,
      shopTab: null,
      selectedMapId: initial.profile?.highestUnlockedMap ?? 1,
      progression: initial,
      lastResult: null,
      pendingImport: null,
      saveMessage: null,
    });
    // A replaced/reset profile can lock the selected map: fall back to the highest unlocked one,
    // otherwise «Начать забег» would silently refuse to start (Task 08.5 fix).
    service.subscribe((progression) => {
      const profile = progression.profile;
      const selected = state!.selectedMapId;
      update({
        progression,
        selectedMapId:
          profile && !isMapUnlocked(profile, selected) ? profile.highestUnlockedMap : selected,
      });
    });
    // Commit each resolved campaign run exactly once (also idempotent in applyRunResult).
    alphaBridge.subscribe(() => {
      const world = alphaBridge.getSnapshot().world;
      if (world) commitResolved(world);
    });
    // Reload/close during a run abandons it; commit that synchronously before the page goes away.
    globalThis.addEventListener?.('pagehide', () => {
      const world = alphaBridge.getSnapshot().world;
      if (world?.campaign?.status === 'active') commitResolved(world, 'abandoned');
    });
  }
  return state!;
}
const committed = new Set<string>();
function commitResolved(world: GameplaySnapshot, outcome?: RunResult['outcome']) {
  const result = runResultFrom(world, outcome);
  if (!result || committed.has(result.runId) || !service) return;
  if (!service.getState().profile) return; // load error: nothing may change
  committed.add(result.runId);
  const commit = service.commitRun(result, new Date().toISOString());
  update({ lastResult: Object.freeze({ runId: result.runId, result, commit }) });
}
/** Applies one gear change through the validated save path; returns a refusal reason or null. */
function gearChange(change: (p: PlayerProfile) => PlayerProfile): string | null {
  const profile = ensure().progression.profile;
  if (!profile) return 'no-profile';
  let next: PlayerProfile;
  try {
    next = change(profile);
  } catch (error) {
    return error instanceof EquipmentError ||
      error instanceof UpgradeError ||
      error instanceof PetError
      ? error.reason
      : 'invalid';
  }
  const written = campaignStore.service().replaceProfile(next);
  return written.ok ? null : (written.failure ?? 'not-saved');
}
function update(patch: Partial<CampaignUiState>) {
  state = Object.freeze({ ...ensure(), ...patch });
  listeners.forEach((fn) => fn());
}

export const campaignStore = {
  getSnapshot: (): CampaignUiState => ensure(),
  subscribe(fn: () => void) {
    ensure();
    listeners.add(fn);
    return () => {
      listeners.delete(fn);
    };
  },
  service(): ProgressionService {
    ensure();
    return service!;
  },
  setPage(page: MenuPage) {
    update({ page, viewClass: null, forgeItem: null, shopTab: null });
  },
  /** Task 13: open Equipment / Talents for a class without selecting it (presentation only). */
  openForClass(page: 'equipment' | 'talents', characterClass: CharacterClass | null) {
    update({ page, viewClass: characterClass });
  },
  /** Task 19: open the forge with an item preselected (presentation only). */
  openForge(itemId: string | null) {
    update({ page: 'forge', viewClass: null, forgeItem: itemId, shopTab: null });
  },
  /** Task 20: open the shop on a tab (presentation only). */
  openShop(tab: string | null) {
    update({ page: 'shop', viewClass: null, forgeItem: null, shopTab: tab });
  },
  selectMap(mapId: number) {
    const profile = ensure().progression.profile;
    if (profile && isMapUnlocked(profile, mapId)) update({ selectedMapId: mapId });
  },
  selectClass(characterClass: CharacterClass) {
    campaignStore.service().selectClass(characterClass);
  },
  /**
   * Task 11: shop purchase — Gold deducted and the item owned in one validated save. Returns the
   * refusal reason (no change) or null on success.
   */
  buyItem(itemId: string): string | null {
    return gearChange((p) => buyItem(p, itemId));
  },
  /** Task 11: equip an owned eligible item for a class (applies to that class's next run). */
  equipItem(characterClass: CharacterClass, itemId: string): string | null {
    return gearChange((p) => equipItem(p, characterClass, itemId));
  },
  /**
   * Task 19 forge: upgrade an owned item by one level — Gold, ore and the level in one validated
   * save (nothing changes when the write fails). Returns the refusal reason or null.
   */
  upgradeItem(itemId: string): string | null {
    return gearChange((p) => upgradeProfileItem(p, itemId));
  },
  /** Task 20: buy a shop pet (Gold deducted and the pet owned in one validated save). */
  buyPet(petId: string): string | null {
    return gearChange((p) => buyProfilePet(p, petId));
  },
  /** Task 20: the one active pet for every class (null = none). */
  setActivePet(petId: string | null): string | null {
    return gearChange((p) => setProfileActivePet(p, petId));
  },
  /** Task 20 forge: pet level +1 (Gold, ore and the level in one validated save). */
  upgradePet(petId: string): string | null {
    return gearChange((p) => upgradeProfilePet(p, petId));
  },
  /** Task 11: unequip a slot (weapon → starter weapon, other slots → empty). */
  unequipSlot(characterClass: CharacterClass, slot: GearSlot): string | null {
    return gearChange((p) => unequipSlot(p, characterClass, slot));
  },
  /**
   * Quit to the menu. An active campaign run is resolved as abandoned (no rewards) first; the
   * world, not the UI, decides the outcome. Finished runs just return to the menu.
   */
  quitToMenu() {
    const world = alphaBridge.getSnapshot().world;
    if (world?.campaign?.status === 'active') alphaBridge.send({ type: 'abandon' });
    update({ page: 'hub' });
    alphaBridge.send({ type: 'menu' });
  },
  /**
   * Task 08.5 crash path: the active run is dropped without any save write, so neither the
   * results commit nor the `pagehide` abandon can touch the save for it afterwards.
   */
  discardActiveRun(): void {
    const runId = alphaBridge.getSnapshot().world?.campaign?.runId;
    if (runId) committed.add(runId);
  },
  /**
   * Task 08.5 §3.3 «Сообщить о проблеме»: downloads a report (build, seed, run, stats, recent
   * errors, validated save, user agent). Read-only: nothing in the save changes.
   */
  downloadReport(): string | null {
    const now = new Date().toISOString();
    const bridge = alphaBridge.getSnapshot();
    const report = buildBugReport({
      createdAt: now,
      build: { version: __APP_VERSION__, commit: __APP_COMMIT__, label: BUILD_LABEL },
      userAgent: globalThis.navigator?.userAgent ?? 'unknown',
      world: bridge.world,
      screen: bridge.screen,
      profile: ensure().progression.profile,
      errors: readErrors(),
    });
    const filename = reportFilename(now);
    return downloadJson(filename, JSON.stringify(report, null, 2)) ? filename : null;
  },
  /** Export: validated profile → JSON download. Read-only; nothing is changed. */
  exportSave(): boolean {
    const profile = ensure().progression.profile;
    if (!profile) return false;
    const out = exportProfile(profile, new Date().toISOString());
    if (!out.ok) {
      update({ saveMessage: { tone: 'error', text: LOAD_ERROR_TEXT[out.error.code] } });
      return false;
    }
    if (!downloadJson(out.filename, out.json)) {
      update({ saveMessage: { tone: 'error', text: 'Не удалось скачать файл.' } });
      return false;
    }
    update({ saveMessage: { tone: 'ok', text: `Сохранение экспортировано: ${out.filename}` } });
    return true;
  },
  /** Import step 1: parse → validate → migrate. Nothing is replaced until confirmImport(). */
  stageImport(text: string, fileName: string) {
    const parsed = prepareImport(text);
    if (!parsed.ok)
      update({
        pendingImport: null,
        saveMessage: {
          tone: 'error',
          text: `Файл не импортирован: ${LOAD_ERROR_TEXT[parsed.error.code]} Текущее сохранение не изменено.`,
        },
      });
    else update({ pendingImport: { profile: parsed.profile, fileName }, saveMessage: null });
  },
  cancelImport() {
    update({ pendingImport: null, saveMessage: null });
  },
  /** Import step 2 (after confirmation): replace the profile; any failure changes nothing. */
  confirmImport() {
    const pending = ensure().pendingImport;
    if (!pending) return;
    const r = campaignStore.service().replaceProfile(pending.profile);
    update({
      pendingImport: null,
      selectedMapId: r.ok ? pending.profile.highestUnlockedMap : ensure().selectedMapId,
      saveMessage: r.ok
        ? { tone: 'ok', text: 'Сохранение импортировано.' }
        : {
            tone: 'error',
            text: `Импорт не выполнен: ${r.failure ? SAVE_FAILURE_TEXT[r.failure] : ''} Текущее сохранение не изменено.`,
          },
    });
  },
  /** Task 09: buy the next rank of a talent node (validated, autosaved). */
  purchaseTalent(characterClass: CharacterClass, nodeId: string) {
    const result = campaignStore.service().purchaseTalent(characterClass, nodeId);
    if (result.ok && !result.saved)
      update({
        saveMessage: {
          tone: 'error',
          text: 'Талант изучен, но прогресс не сохранён. Повторите сохранение в «Настройках».',
        },
      });
    return result;
  },
  retrySave() {
    const ok = campaignStore.service().retrySave();
    update({
      saveMessage: ok
        ? { tone: 'ok', text: 'Прогресс сохранён.' }
        : { tone: 'error', text: 'Сохранить всё ещё не удаётся.' },
    });
  },
  /**
   * Starts a campaign run on an unlocked map with the class's permanent level. Every run gets a
   * new seed unless one is given (Task 08.5 §4.2: the debug tools replay a seed).
   */
  startRun(
    mapId = ensure().selectedMapId,
    characterClass?: CharacterClass,
    seed: number = generateRunSeed(),
  ): boolean {
    if (!Number.isSafeInteger(seed) || seed < 0 || seed > MAX_UI_SEED)
      throw new RangeError(`Seed must be a whole number 0–${MAX_UI_SEED}.`);
    const profile = ensure().progression.profile;
    if (!profile || !isMapUnlocked(profile, mapId)) return false;
    getCampaignMap(mapId);
    const cls = characterClass ?? profile.selectedClass;
    if (cls !== profile.selectedClass) campaignStore.service().selectClass(cls);
    update({ selectedMapId: mapId });
    alphaBridge.send({
      type: 'start',
      options: {
        characterClass: cls,
        level: profile.classes[cls].level,
        seed,
        // Task 09: the class's talents apply from run start; changes affect the next run.
        talents: { ranks: profile.classes[cls].talents },
        // Task 11: this class's own loadout; changes apply to the next run.
        equipment: { loadout: profile.classes[cls].loadout, itemLevels: profile.itemLevels },
        // Task 20: the profile's one active pet comes with whichever class starts the run.
        pet: activePetOf(profile),
        campaign: { mapId, runId: generateRunId() },
      },
    });
    return true;
  },
};
/** Task 20: the run option for the profile's active pet (null = none). */
export function activePetOf(profile: PlayerProfile): Readonly<{ id: PetId; level: number }> | null {
  const id = profile.activePet;
  return id && isPetId(id) ? Object.freeze({ id, level: petLevel(profile.petLevels, id) }) : null;
}
